                    <p>We retain personal information for the following periods:</p>
                    <ul>
                        <li><strong>Active accounts:</strong> For as long as your account remains active</li>
                        <li><strong>Cancelled accounts:</strong> 90 days after cancellation, then permanently deleted</li>
                        <li><strong>Payment records:</strong> 5 years as required by South African tax law</li>
                        <li><strong>QR scan logs:</strong> 12 months for security and audit purposes</li>
                        <li><strong>Support communications:</strong> 2 years</li>
                    </ul>
                    <p>After retention periods expire, data is securely deleted or anonymised.</p>

                    <h2 id="security">7. Data Security</h2>
                    <p>We implement industry-standard technical and organisational measures to protect your personal information, including:</p>
                    <ul>
                        <li>HTTPS/TLS encryption for all data in transit</li>
                        <li>Bcrypt password hashing (passwords are never stored in plain text)</li>
                        <li>CSRF token protection on all forms</li>
                        <li>SQL injection prevention through prepared statements</li>
                        <li>Regular security audits and updates</li>
                        <li>Restricted staff access on a need-to-know basis</li>
                    </ul>
                    <p>While we take every reasonable precaution, no system is 100% secure. In the event of a data breach affecting your rights, we will notify you and the Information Regulator within the timeframes required by POPIA.</p>

