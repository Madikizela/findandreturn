                        <li><strong>QR Code Notifications:</strong> To alert you when a QR code linked to your profile is scanned</li>
                        <li><strong>Communication:</strong> To send service-related emails and SMS notifications</li>
                        <li><strong>Payment Processing:</strong> To manage subscriptions and process transactions</li>
                        <li><strong>Legal Compliance:</strong> To comply with applicable South African laws</li>
                        <li><strong>Security:</strong> To prevent fraud and protect users</li>
                        <li><strong>Service Improvement:</strong> To analyse usage and improve our platform</li>
                    </ul>
                    <p>We do <strong>not</strong> process your information for automated decision-making that significantly affects you, nor for direct marketing without your explicit consent.</p>

                    <h2 id="sharing">5. Sharing of Personal Information</h2>
                    <p>We do not sell your personal information. We may share it only in the following circumstances:</p>
                    <ul>
                        <li><strong>Service Providers:</strong> Trusted third parties such as email service providers (PHPMailer/SMTP), WhatsApp notification services, and payment processors — bound by confidentiality agreements</li>
                        <li><strong>School Administrators:</strong> Schools you are affiliated with may see your child's name, grade, and QR code status (not your personal contact details)</li>
                        <li><strong>Item Finders:</strong> When a QR code is scanned, limited information is displayed to assist with item return</li>
                        <li><strong>Legal Requirements:</strong> When required by South African law, court order, or law enforcement</li>
                        <li><strong>Business Transfer:</strong> In the event of a merger or acquisition, with appropriate privacy protections</li>
                    </ul>

